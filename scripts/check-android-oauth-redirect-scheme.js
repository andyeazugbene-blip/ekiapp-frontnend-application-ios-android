#!/usr/bin/env node
/**
 * check-android-oauth-redirect-scheme
 *
 * Real bug this guards against: expo-auth-session's Google provider
 * (node_modules/expo-auth-session/build/providers/Google.js) does not use
 * the app's own "ekiapp" scheme for its native OAuth redirect — it builds
 * `${Application.applicationId}:/oauthredirect` by default, i.e.
 * "com.ekiapp.mobile:/oauthredirect" on Android (matching Google's own
 * documented convention of using the app's package name as the native
 * redirect scheme). The checked-in Android manifest only had an
 * intent-filter for "ekiapp" and was missing one for the app's own package
 * name, so Google Sign-In on Android (Play Store build) had nowhere to
 * deliver its response.
 *
 * android/ is a checked-in, manually-maintained native project here (not
 * regenerated by `expo prebuild` on every build — see git history of
 * android/app/build.gradle for prior manual version-code fixes), so
 * app.json's `scheme` array alone does NOT guarantee this intent-filter
 * exists in the real build; the manifest itself is the source of truth and
 * is what this check reads.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const MANIFEST_PATH = path.join(ROOT, "android", "app", "src", "main", "AndroidManifest.xml");
const BUILD_GRADLE_PATH = path.join(ROOT, "android", "app", "build.gradle");

if (!fs.existsSync(MANIFEST_PATH)) {
  console.log("check-android-oauth-redirect-scheme skipped: no android/ directory (not a bare/checked-in Android project).");
  process.exit(0);
}

const buildGradle = fs.readFileSync(BUILD_GRADLE_PATH, "utf8");
const packageMatch = buildGradle.match(/applicationId\s+['"]([\w.]+)['"]/);
if (!packageMatch) {
  console.error("FAIL check-android-oauth-redirect-scheme: could not find applicationId in android/app/build.gradle.");
  process.exit(1);
}
const packageName = packageMatch[1];

const manifest = fs.readFileSync(MANIFEST_PATH, "utf8");
const expectedTag = `<data android:scheme="${packageName}"/>`;
if (!manifest.includes(expectedTag)) {
  console.error(
    `FAIL check-android-oauth-redirect-scheme: AndroidManifest.xml has no intent-filter <data android:scheme="${packageName}"/> — ` +
      "this is the redirect URI scheme expo-auth-session's Google provider actually uses on Android " +
      `(${packageName}:/oauthredirect), matching the app's own applicationId. Without it, a completed ` +
      "Google Sign-In has no way to return control to the app. Add it alongside the existing \"ekiapp\" " +
      "scheme's <data> entry in the same intent-filter.",
  );
  process.exit(1);
}

console.log("check-android-oauth-redirect-scheme passed.");
